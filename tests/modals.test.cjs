// Run: npm test (all) or npm test <name>
const ROOT = require("node:path").resolve(__dirname, "..");
const H = require("./harness.cjs")(ROOT);
const { d, ok, T, bodyKey, add, unfocus, tick } = H;
const menu = async (action) => { d.getElementById("listMenuBtn").click(); d.querySelector(`[data-action="${action}"]`).click(); await tick(); };
(async () => {
  await tick();
  await add("A"); await unfocus();
  const help = d.getElementById("help"), ai = d.getElementById("aiPanel");
  ok(help.tagName === "DIALOG" && ai.tagName === "DIALOG", "Tastenkürzel und Claude sind <dialog>-Popups");
  ok(help.querySelector(".modal-head h2").textContent.includes("Tastenkürzel") && !!help.querySelector(".modal-close svg"), "mit Überschrift und × in der Ecke");
  await menu("help");
  ok(help.open && d.getElementById("listMenu").hidden, "⋯ → Tastenkürzel öffnet das Popup (Menü zu)");
  help.querySelector(".help-grid kbd").click(); await tick();
  ok(help.open, "Klick in den Inhalt lässt es offen");
  help.dispatchEvent(new H.w.MouseEvent("click", { bubbles: true })); await tick();
  ok(!help.open, "Klick auf den Hintergrund schließt");
  await menu("help");
  const search = d.getElementById("helpSearch"), secs = [...help.querySelectorAll(".help-sec")];
  const type = async (s) => { search.value = s; search.dispatchEvent(new H.w.Event("input")); await tick(); };
  const shown = () => [...help.querySelectorAll(".help-row")].filter((r) => !r.hidden && !r.closest(".help-sec").hidden);
  const openSecs = () => secs.filter((s) => s.open).map((s) => s.dataset.sec).join();
  ok(openSecs() === "sel" && help.querySelector('[data-jump="sel edit both"]').classList.contains("on"), "Hilfe: erster Abschnitt offen, Chip „Liste“ markiert");
  await type("alt verschieben");
  ok(shown().length === 1 && shown()[0].closest(".help-sec").dataset.sec === "both" && shown()[0].closest(".help-sec").open, "Suche: alle Wörter müssen passen, der Treffer-Abschnitt geht auf");
  await type("strg+z");
  ok(shown().length >= 2 && shown().every((r) => r.dataset.t.includes("strg z")), "Suche findet Tastenkombinationen");
  await type("markdown");
  ok(secs.filter((s) => !s.hidden).map((s) => s.dataset.sec).join() === "md" && shown().length > 5, "Treffer im Abschnittstitel zeigt den ganzen Abschnitt");
  await type("z");
  ok(shown().length > 0 && d.getElementById("helpEmpty").hidden, "ein Buchstabe sucht Wortanfänge – das erste Zeichen leert die Liste nicht");
  await type("xyzzy");
  const askBtn = d.getElementById("helpAsk"), aiBox = d.getElementById("helpAi");
  ok(!d.getElementById("helpEmpty").hidden && !askBtn.hidden && askBtn.textContent.includes("„xyzzy“"), "ohne Treffer: „Nichts gefunden.“ und „KI fragen“");
  const altRow = [...help.querySelectorAll(".help-row")].findIndex((r) => r.dataset.t.includes(" alt ↑ ↓ verschieben")) + 1;
  H.helpReply = async () => ({ ok: true, data: { rows: [altRow, 999], answer: "Mit <kbd>Alt</kbd>+<kbd>↑</kbd> nach oben." } });
  await type("aufgabe nach oben bringen");
  const enter = async () => { search.dispatchEvent(new H.w.KeyboardEvent("keydown", { key: "Enter", bubbles: true, cancelable: true })); await tick(); await tick(); };
  await enter();
  ok(H.helpAsks.length === 1 && H.helpAsks[0].question === "aufgabe nach oben bringen" && H.helpAsks[0].rows.includes(`${altRow} | Ausgewählt und beim Bearbeiten | Alt+↑ / ↓ | verschieben`), "Enter fragt die KI mit den Zeilen des Fensters");
  ok(!aiBox.hidden && aiBox.querySelectorAll("kbd").length === 2 && shown().length === 1 && shown()[0].classList.contains("help-ai-hit") && askBtn.hidden, "KI-Antwort mit Tasten; die Liste zeigt nur ihre Zeile (unbekannte Nummern fallen weg)");
  await type("aufgabe nach oben");
  ok(aiBox.hidden && !askBtn.hidden, "weitertippen: zurück zur normalen Suche");
  await type("aufgabe nach oben bringen"); await enter();
  ok(H.helpAsks.length === 1 && !aiBox.hidden && shown().length === 1, "dieselbe Frage nochmal: Antwort aus dem Speicher, keine neue Anfrage");
  H.helpReply = async () => ({ ok: false, error: "Claude: kaputt" });
  await type("noch was"); await enter();
  ok(aiBox.classList.contains("error") && aiBox.textContent.includes("kaputt"), "Fehler der KI wird angezeigt");
  await type("xyzzy");
  search.dispatchEvent(new H.w.KeyboardEvent("keydown", { key: "Escape", bubbles: true, cancelable: true })); await tick();
  ok(help.open && search.value === "" && openSecs() === "sel" && secs.every((s) => !s.hidden) && d.getElementById("helpEmpty").hidden, "Esc leert erst die Suche, die Abschnitte sind wie vorher");
  help.querySelector('[data-jump="chat web ff"]').click(); await tick();
  ok(openSecs() === "chat,web,ff" && help.querySelector('[data-jump="chat web ff"]').classList.contains("on") && !help.querySelector('[data-jump="sel edit both"]').classList.contains("on"), "Chip öffnet nur seine Abschnitte");
  await type("enter");
  help.close();
  await menu("help");
  ok(search.value === "" && openSecs() === "chat,web,ff", "Neu öffnen: Suche leer, Abschnitte wie zuletzt");
  help.close();
  await menu("ai");
  ok(ai.open, "⋯ → Claude einrichten öffnet das Popup");
  await bodyKey("ArrowDown");
  ok(!d.activeElement.classList.contains("md-edit"), "↓ wirkt bei offenem Popup nicht auf die Aufgaben");
  const before = JSON.stringify(H.sync.data);
  await bodyKey("z", { ctrlKey: true });
  ok(JSON.stringify(H.sync.data) === before, "Strg+Z wirkt bei offenem Popup nicht");
  ai.querySelector(".modal-close").click(); await tick();
  ok(!ai.open, "× schließt");
  await bodyKey("z", { ctrlKey: true });
  ok(!T("A"), "nach dem Schließen wirkt Strg+Z wieder");
  H.finish();
})().catch((e) => { console.error(e); process.exit(1); });
